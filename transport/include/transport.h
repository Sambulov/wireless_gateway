#pragma once

#include <stdint.h>
#include <stddef.h>

/* Механизм подписки на события (delegate_t/event_t) — общий для всей прошивки:
 * отдельного списка подписчиков у транспорта нет. */
#include "CodeLib.h"

/* ── Контракт транспорта ─────────────────────────────────────────────────────
 *
 * Транспорт — канал доставки сообщений между удалённой стороной и подписчиком
 * внутри прошивки. Конкретика канала (сокеты, кадры, управляющие сообщения)
 * целиком в реализации; здесь только то, на что опирается подписчик:
 *
 *   • приём: транспорт собирает СООБЩЕНИЕ (фрагменты и кадры складываются в
 *     одно целое) и отдаёт его событием RECEIVED — подписчик работает с уровнем
 *     сообщений, а не кадров;
 *   • передача: подписчик отдаёт сообщение и ждёт события TRANSFER_COMPLETE или
 *     TRANSFER_ERR, потому что отправка асинхронная;
 *   • соединения: транспорт сообщает, когда соединение установлено и когда
 *     разорвано. Дескриптор соединения подписчику непрозрачен — это ключ, по
 *     которому он ведёт своё состояние, и ничего больше;
 *   • подписка на события — делегат (delegate_t): транспорт не разбирает
 *     обработчик и контекст по отдельности, а поднимает событие через
 *     event_raise. Отписки в контракте нет: её делает сам подписчик
 *     (event_unsubscribe), для транспорта это просто отсутствие делегата.
 *
 * Кто подписчик, транспорт не знает и знать не должен: содержимое сообщений он
 * не интерпретирует и решений за подписчика не принимает.
 *
 * Экземпляр, а не «транспорт вообще». Реализация создаёт независимые экземпляры:
 * у каждого СВОЙ контекст (объект реализации), свои соединения и свои
 * подписчики, события одного не видны другому. Экземпляр описан структурой
 * transport_t (ниже) — методы вместе с контекстом; именно её получает
 * подписчик. Идентификатор экземпляра — указатель на контекст: он уникален и
 * живёт столько же, сколько экземпляр, поэтому «тот же транспорт» проверяется
 * сравнением контекстов.
 *
 * Роли `self` в методах:
 *   init / open / subscribe — операции экземпляра: self — его контекст;
 *   close / begin_send / break_sending — операции соединения: self — дескриптор
 *                              соединения, он же приходит в событиях.
 */

/* Длина потока неизвестна: транспорт уровня сообщений всегда отдаёт сообщение
 * целиком, поэтому в событиях RECEIVED/COMPLETE/ERR поле left == 0. */
#define TRANSPORT_STREAM_LENGTH  0xffffffffu

typedef enum {
    TRANSPORT_OPEN              = 0x01, /* экземпляр начал принимать соединения */
    TRANSPORT_ESTABLISHED       = 0x02, /* установлено новое соединение */
    TRANSPORT_CLOSED            = 0x04, /* соединение разорвано: ресурсы можно освобождать */
    TRANSPORT_TRANSFER_BUFFER   = 0x10, /* транспорт даёт буфер под отправку */
    TRANSPORT_TRANSFER_COMPLETE = 0x20, /* отправка завершена */
    TRANSPORT_TRANSFER_ERR      = 0x40, /* отправка не удалась */
    TRANSPORT_RECEIVED          = 0x80, /* принято сообщение */
} transport_event_type_t;

typedef enum {
    TRANSPORT_INVALID  = 0x00,
    TRANSPORT_OK       = 0x01,
    TRANSPORT_BUSY     = 0x02,
    TRANSPORT_BAD_CALL = 0x04,
    TRANSPORT_FAULT    = 0x08,
} transport_result_t;

typedef struct {
    transport_event_type_t event;
    union {
        /* RECEIVED: ptr — собранное сообщение целиком, length — его длина,
         *           left == 0 (см. TRANSPORT_STREAM_LENGTH).
         * TRANSFER_COMPLETE/ERR: ptr — ровно тот указатель, который подписчик
         *           отдал в begin_send, length — его длина. Указатель обязан
         *           вернуться неизменным: по нему подписчик находит свой блок.
         * Данные принадлежат транспорту: подписчик их не освобождает и не
         * изменяет, они живут до возврата из обработчика события. */
        struct { const void *ptr; uint32_t length; uint32_t left; } data;
        /* TRANSFER_BUFFER — «вот буфер, пиши в него». Реализациям, которые
         * буфер держат и отправляют сами, это событие не нужно; тип оставлен,
         * чтобы интерфейс покрывал и такой стиль работы. */
        struct { void *ptr; uint32_t size; uint32_t fill; } buffer;
    };
} transport_event_trigger_t;

/* Аргументы обработчика делегатные (event_handler_t из CL/Workflow/Event.h):
 *   event_trigger — событие транспорта (const transport_event_trigger_t *);
 *   sender        — дескриптор соединения, о котором событие;
 *   context       — то, что подписчик положил в СВОЙ delegate_t: по нему
 *                   обработчик находит своё состояние (подписчиков бывает
 *                   несколько, общий обработчик на всех не годится).
 *
 * События одного экземпляра поднимаются по одному: event_raise помечает
 * делегатов, которых уже обходит, поэтому поднимать новое событие того же
 * экземпляра из обработчика нельзя — оно не дойдёт до того, кто занят
 * предыдущим. */

typedef struct {
    /* Подготовить экземпляр к работе. config — настройки экземпляра, вид
     * структуры задаёт реализация; зовётся один раз, при создании экземпляра. */
    transport_result_t (*init)(const void *self, const void *config);
    /* Начать принимать соединения и отдавать их подписчику. Вызывается ПОСЛЕ
     * подписки (subscribe): иначе первое соединение отдавать некому. */
    transport_result_t (*open)(const void *self, const void *config);
    /* Разорвать соединение и освободить его ресурсы. */
    transport_result_t (*close)(const void *self);
    /* Отправить СООБЩЕНИЕ (кадры строит транспорт). Асинхронно: результат
     * приходит событием TRANSFER_COMPLETE/TRANSFER_ERR, данные должны жить до
     * него. Возврат != TRANSPORT_OK — отправка не принята и события не будет,
     * буфер освобождает подписчик. */
    transport_result_t (*begin_send)(const void *self, const void *data, uint32_t length);
    /* Прервать начатую отправку, если реализация умеет частичную отмену. */
    transport_result_t (*break_sending)(const void *self);
    /* Подписаться на события экземпляра: делегат кладётся в event_t реализации,
     * событие поднимается через event_raise, и обработчик получает контекст
     * подписчика из своего делегата. */
    transport_result_t (*subscribe)(const void *self, delegate_t *delegate);
    /* Числовой идентификатор соединения (необязателен, может быть NULL):
     * сокетный транспорт отдаёт номер сокета. Нужен только для журнала — по
     * нему видно, о каком соединении речь. */
    int32_t (*peer_id)(const void *self);
} transport_iface_t;

/* ── Объект транспорта ──────────────────────────────────────────────────────
 *
 * Методы вместе с контекстом реализации: подписчик получает один объект, и
 * половины от разных экземпляров разойтись не могут. Структура раскрыта
 * сознательно — это слой интерфейса, а не состояние; логики в полях нет.
 *
 * Полей два, и оба про экземпляр: чем он умеет и чей он. Номер сетевого
 * интерфейса сюда не входит: это свойство того, кто экземпляр породил, и если
 * реализации он нужен, она держит его в своём контексте. */
typedef struct {
    const transport_iface_t *iface;   /* методы транспорта */
    void *context;                    /* контекст реализации; он же идентификатор */
} transport_t;
