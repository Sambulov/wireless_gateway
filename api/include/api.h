#ifndef NWWEB_H_INCLUDED
#define NWWEB_H_INCLUDED

#include <stdint.h>
#include <stddef.h>

/* Заголовков ESP-IDF здесь нет: подъём ядра возвращает указатель, а не код
 * ошибки IDF (см. api_init). Файлы, которым код ошибки нужен сами, включают его
 * сами.
 *
 * platform.h здесь ТОЖЕ не включается: ядро не знает ни платформенных имён, ни
 * FreeRTOS, ни ESP-IDF. Всё, что ядру нужно от системы, приходит таблицей
 * api_system_t (ниже), а платформа (мьютексы, очереди, время, задачи, журнал)
 * остаётся отдельным компонентом platform/ для приложения и сервисов. */
#include "transport.h"

/* ── Дескриптор ядра ────────────────────────────────────────────────────────
 *
 * Ядро API — экземпляр: api_init заводит дескриптор и возвращает его указателем,
 * а вызывающий хранит этот указатель и передаёт его функциям ядра. Сколько ядер
 * поднято — столько дескрипторов; в прошивке их два (точка доступа и станция), и
 * общего у них нет ничего.
 *
 * Раскладка состояния наружу не раскрывается — так же, как у gw_uart_t (см.
 * uart.h и seg_ring.h): снаружи только неполный тип, всё остальное — дело
 * api/src/api_core.c. Размер дескриптора снаружи знать незачем: его выделяет и
 * освобождает само ядро. */
typedef struct api_s api_t;

/* ── Что ядру нужно от системы ──────────────────────────────────────────────
 *
 * РОВНО три вещи: мьютекс, чтение таймера и журнал. Ни очередей, ни задержек,
 * ни создания потоков ядро не просит и не делает само — в этом и состоит
 * кооперативный контракт: ядро не имеет права ни ждать, ни заводить себе
 * исполнителя.
 *
 * КАЖДЫЙ вызов принимает системный контекст (context) первым аргументом: у
 * системы может быть своё состояние (в прошивке — объект приложения), и ядро не
 * должно знать, чьё оно. Ядро только передаёт его обратно.
 *
 * Мьютекс должен быть РЕКУРСИВНЫМ: ядро берёт его на время работы со списками и
 * внутри этой критической секции зовёт обработчик, а тот отвечает через
 * api_reply — то есть берёт тот же мьютекс повторно. mutex_take возвращает
 * управление с уже взятым мьютексом (в прошивке — без предела ожидания):
 * «не взялся» — это ошибка системы, и разбирать её ядру нечем.
 *
 * log — varargs-функция, а не готовая строка: ядро передаёт fmt и аргументы, а
 * как их вывести, решает система. Уровни — API_LOG_* (ниже), а не уровни
 * ESP-IDF: ядро про него не знает.
 *
 * time_ms — монотонное время в миллисекундах (в нём выражены ARG.RDL и период
 * такта). Ядро читает его в такте и сравнивает разности; спать по нему оно не
 * умеет и не должно. */
typedef struct {
    void *context;                                        /* объект системы */
    void *(*mutex_create)(void *context);
    void  (*mutex_take)(void *context, void *mutex);
    void  (*mutex_give)(void *context, void *mutex);
    uint32_t (*time_ms)(void *context);                    /* чтение таймера */
    void  (*log)(void *context, int level, const char *tag, const char *fmt, ...);
} api_system_t;

/* Уровни журнала ядра. Числами, а не уровнями ESP-IDF: ядро его не знает, а
 * система переводит их в свои (см. main/app.c). */
#define API_LOG_DEBUG  0
#define API_LOG_INFO   1
#define API_LOG_WARN   2

/* Темп такта ядра, мс. Ядро не спит само — паузу между тактами держит тот, кто
 * зовёт api_worker (в прошивке — задача приложения). Обработчики получают такт не
 * чаще раза в миллисекунду: иначе обработчик пульса вызывался бы чаще, чем ему
 * есть что делать. */
#define API_WORK_PERIOD_MS 1

/* FID — текстовое имя вида "<подсистема>.<действие>": "wifi.sta", "uart2.modbus".
 * Клиент присылает его строкой, сервер возвращает то же имя в ответе. Самое
 * длинное имя — "uart2.config" (12 символов), 24 хватает с запасом. Отсутствие
 * имени — это пустая строка или NULL, отдельного «нулевого кода» нет. */
#define API_FID_NAME_MAX 24

/* ── Статусы, которые отправляет САМО ядро ──────────────────────────────────
 *
 * Ровно те четыре, которые ядро кладёт в ответ без участия обработчика:
 * подтверждение приёма, отказ в разборе, отсутствие обработчика и отказ
 * «обработчик исчез». Свой статус обработчик собирает сам своим json-ом
 * (в прошивке — "STA" из main/apih_sys_internal.h) и отдаёт одним
 * api_reply. */
#define API_CALL_STATUS_INVALID                     0x00000004
#define API_CALL_STATUS_DELIVERED                   0x00000005

#define API_CALL_ERROR_STATUS_BAD_REQ               0x80000000
#define API_CALL_ERROR_STATUS_NO_HANDLER            0x8000000E

/*!
	@brief Обработчик вызова API — единственный путь доставки запроса сервису.

	Ядро зовёт его в такте работы: сначала с запросом клиента, а дальше — с
	data == NULL в каждом такте, пока обработчик не завершит вызов. Поэтому
	обработчик обязан быть неблокирующим: если нужно ждать периферию, он
	возвращает TRUE и завершает работу позже, а не крутится внутри.

	Ядро обработчику НЕ передаётся: ответ адресован вызову, и api_reply
	берёт ядро из самого вызова — отвечающему знать его незачем, а хранить
	(например, чтобы ответить из своего потока) достаточно дескриптор
	вызова. Рассылку по имени делает тот, кто знает СВОЁ ядро, — сервис,
	хранящий дескрипторы, на которых зарегистрирован (см. api_broadcast), —
	а не обработчик: у него ядра нет.

	ВОЗВРАТ — ЭТО И ЕСТЬ ЗАВЕРШЕНИЕ ВЫЗОВА, отдельного «завершить» в контракте
	нет:
	  * FALSE — вызов завершён; ядро снимает его сразу после возврата и больше
	    не зовёт (единственное исключение — подписка, см. ниже). Контекст
	    вызова (*context) обработчик освобождает сам.
	  * TRUE  — работа не закончена; ядро вызовет обработчик снова следующим
	    тактом (data == NULL), и так до FALSE.

	ОТВЕТ ДАЁТСЯ ОДИН РАЗ ЗА ВЫЗОВ: клиенту уходит либо api_reply из
	этого обработчика, либо отказ самого ядра (DELIVERED/BAD_REQ/NO_HANDLER) —
	если ответа не было до FALSE, вызов закрывается молча, и клиент останется
	без ответа. Повторная отправка — это два кадра на один вызов, и разбирать
	их клиенту нечем.

	ПОДПИСКА (клиент прислал FLAGS с битом 4) не закрывается: ядро
	переспрашивает её само. FALSE здесь означает «на этот опрос ответ дан», и
	вызов вернётся к обработчику заново по ARG.RDL (или сразу, если RDL нет) —
	уже как обычный запрос клиента, с теми же данными; TRUE — «ответа ещё нет»,
	следующим будет такт работы. Снимает подписку клиент (FLAGS с битом удаления)
	или уход соединения — тогда обработчик получает call == NULL и обязан
	вернуть FALSE.

	@param[in] call      дескриптор вызова. NULL — принудительное завершение:
	                     клиент ушёл или соединение разорвано. Обработчик
	                     обязан освободить свой контекст (*context) и вернуть
	                     FALSE (допускается за несколько вызовов).
	@param[in,out] context контекст вызова, принадлежащий обработчику. При
	                     первом вызове нового запроса содержит контекст,
	                     переданный при регистрации. Пустой *context означает
	                     первичный вызов (например, подписка), заполненный —
	                     повторный.
	@param[in] data      для запроса клиента ВСЕГДА не NULL (может указывать на
	                     пустой payload, если ARG не было). data == NULL при
	                     живом вызове — такт работы: обработчик может сделать
	                     свою периодическую работу (например, выдать кадр
	                     подписки). Данные запроса ПОСЛЕ ответа ядру не
	                     принадлежат: распоряжаться ими (и помнить указатель
	                     между тактами) нельзя.
	@param[in] data_len  длина data (0, если ARG не было).
	@return TRUE  — вызов остаётся активным;
	        FALSE — вызов завершён (вызова завершения после этого не будет).
*/
typedef uint8_t (*api_handler_t)(void *call, void **context, uint8_t *data,
                                 uint32_t data_len);

/* Регистрация сервиса на КОНКРЕТНОМ ядре.
 *
 * Доставка запроса сервису — это ВЫЗОВ ЕГО ОБРАБОТЧИКА, и другого пути у ядра
 * нет: очередей периферии в ядре не существует. Обработчик либо отвечает сразу
 * и возвращает FALSE, либо возвращает TRUE — и тогда ядро вызовет его снова на
 * следующем такте. Если сервису нужен свой поток или своя очередь (например, он
 * ждёт ответа от прибора), это его внутреннее дело: он складывает вызов у себя
 * и отвечает через api_reply — ядру об этом знать нечего.
 *
 * Снять регистрацию нечем и не нужно: набор сервисов задаётся при подъёме ядра и
 * живёт до api_deinit (в прошивке — до перезагрузки). Функции снятия в контракте
 * нет: без неё в ядре нет и второго пути «вызов есть, а обработчика уже нет».
 *
 * Маски интерфейсов здесь нет: ядро не решает, «кому» оказан сервис, — у каждого
 * ядра свой транспорт (в прошивке их два: точка доступа и станция), и вызов
 * приходит в то ядро, на котором сервис зарегистрирован. Политика «этот клиент
 * может менять, а тот нет» выражена не маской, а тем, на каком ядре
 * зарегистрирован обработчик и какой контекст (context) ему дан: обработчик по
 * контексту и понимает, что этому клиенту можно.
 *
 * Ключ регистрации — имя FID. На одном ядре имя регистрируется один раз: две
 * одинаковые регистрации неразличимы, вторую отвергаем. На разных ядрах одно и
 * то же имя регистрируется свободно — это и есть «один метод, разное поведение
 * на разных транспортах».
 *
 * Вызов из соединения ядра, у которого сервиса нет, получает
 * API_CALL_ERROR_STATUS_NO_HANDLER. */
uint8_t api_register_handler(api_t *api, api_handler_t handler, const char *name,
                             void *context);

/* ── Подъём и снятие ядра ───────────────────────────────────────────────────
 *
 * api_init СОЗДАЁТ ядро и возвращает его дескриптор (NULL — поднять не удалось:
 * нет транспорта или системы, интерфейс неполон, не хватило памяти). Память
 * дескриптора принадлежит ядру, а не вызывающему: вызывающий только хранит
 * указатель.
 *
 * Всё, что ядру нужно снаружи, — два объекта, и оба приходят на вход. Транспорт
 * (transport_t): методы и контекст реализации (он же — идентификатор экземпляра);
 * ядро подписывается на события ЧЕРЕЗ ЭТОТ объект (subscribe отдаёт СВОЙ делегат с
 * обработчиком и контекстом — см. transport.h). Система (api_system_t): объект
 * системы и три операции — мьютекс, время, журнал. Выбор «какое ядро над каким
 * транспортом» и «какая у него система» — дело вызывающего (main/app.c), а не
 * ядра.
 *
 * Ядро НЕ заводит себе ни задачи, ни очереди: такт ему даёт api_worker. Поэтому
 * поднять и снять ядро можно и там, где задач нет вовсе (на хосте), и там, где
 * есть (в прошивке).
 *
 * Таблицы системы хватает на всё время жизни ядра: копию ядро не делает (и не
 * может — там указатели на функции). */
api_t *api_init(const transport_t *transport, const api_system_t *system);
/* Снять ядро: отписаться от транспорта, освободить вызовы, регистрации, сессии
 * и сам дескриптор. Нужно тестам (каждый тест поднимает своё ядро) и тем, кто
 * перезапускает ядро на ходу; прошивка не зовёт: там ядро живёт до перезагрузки.
 * Мьютекс ядра освобождает система — в api_deinit его удалять нечем и не нужно:
 * на цели ядро умирает вместе с системой. */
void   api_deinit(api_t *api);

/* Один такт работы ядра. Зовёт ВЫЗЫВАЮЩИЙ — одной задачей на все ядра
 * (в прошивке — задачей приложения, по вызову на ядро с паузой между тактами).
 * В такте: новые запросы отдаются обработчикам, обработчики получают своё
 * периодическое дело, подписки переспрашивают периферию по ARG.RDL, вызовы без
 * соединения просят завершения, завершённые снимаются — но только после того,
 * как обработчик вернул FALSE.
 *
 * Такт НЕ ЖДЁТ: всё, что ядро не успело, оно оставляет на следующий вызов (для
 * этого обработчик возвращает TRUE). Один такт — один проход, без циклов
 * ожидания внутри.
 *
 * api == NULL — не такт, а ничего: вызывающему не нужно помнить, поднялось ли
 * ядро. */
void   api_worker(api_t *api);

/* ── Ответ клиенту ──────────────────────────────────────────────────────────
 *
 * Оба входа ниже — ЕДИНСТВЕННЫЙ способ отдать кадр клиенту, и оба зовёт сервис:
 * ядро само собирает конверт {"FID":..,"SID":..,"ARG":<json>} и отдаёт его
 * транспорту. Адресат ответа — дескриптор вызова.
 *
 * Ядро явное только у рассылки: соединения, подписки и общий буфер ответа
 * принадлежат конкретному ядру, и рассылающий знает своё ядро (сервис хранит
 * дескрипторы, на которых зарегистрирован). Ответу ядро не нужно: адресат —
 * дескриптор вызова, и вызов помнит своё ядро сам. */
/* Ответ конкретному вызову (json — готовый фрагмент ARG, не конверт).
 * json КОПИРУЕТСЯ в буфер ядра (он живёт до события завершения отправки),
 * поэтому данные вызывающего остаются его: освобождать их после ответа можно и
 * хранить указатель между тактами незачем.
 * Возврат: 1 — отправка принята транспортом; 0 — вызов не задан (call == NULL),
 * вызов без соединения или транспорт отказал. Вызов от отказа не меняется. */
uint8_t api_reply(void *call, const uint8_t *json, uint32_t len);
/* Рассылка по имени FID адресована не вызову, а всем подписчикам имени — на
 * всех соединениях ОДНОГО ядра. Конверт собирается ОДИН раз на всех
 * получателей (одна копия данных, а не по копии на клиента). */
uint8_t api_broadcast(api_t *api, const char *name, const uint8_t *json,
                            uint32_t len);

#endif /* NWWEB_H_INCLUDED */
