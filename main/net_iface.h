/* ── Сетевой интерфейс прибора ───────────────────────────────────────────────
 *
 * Через какой интерфейс пришёл клиент: наша точка доступа, наша станция (мы
 * клиент чужой точки) или провод. Понятие сетевого уровня — транспорту и ядру
 * API оно не нужно: транспорт вообще не спрашивают про интерфейс (какой
 * интерфейс обслуживать, решает тот, кто породил экземпляр), а ядро API
 * работает с тем транспортом, который ему дали.
 *
 * Нужно это веб-серверу и его сокетному слою (какой объект сервера обслуживает
 * соединение) и политике доступа к HTTP-путям.
 */

#define GW_IFACE_NONE  0u   /* интерфейс неизвестен (определить не удалось) */
#define GW_IFACE_AP    1u   /* клиент нашей точки доступа */
#define GW_IFACE_STA   2u   /* мы сами клиент чужой точки доступа */
#define GW_IFACE_ETH   3u   /* проводной интерфейс (задел; пока только QEMU) */
#define GW_IFACE_LAST  GW_IFACE_ETH

/* Маска интерфейсов — язык веб-политики: GW_IFACE_MASK(GW_IFACE_AP) — только AP.
 * Маски складываются: GW_IFACE_MASK(GW_IFACE_AP) | GW_IFACE_MASK(GW_IFACE_STA). */
#define GW_IFACE_MASK(iface)  (1u << (iface))
/* «Любой интерфейс», включая неизвестный: сервис не различает, откуда клиент. */
#define GW_IFACE_MASK_ANY     0xffffffffu
/* «Никакой интерфейс» — такой сервис не нужен никому. */
#define GW_IFACE_MASK_NONE    0u
