/* Общая обвязка системных сервисов: то, что нужно всем файлам служб
 * (apih_wifi.c, apih_device.c, apih_files.c, apih_fw.c) и не принадлежит ни
 * одному из них.
 *
 * Здесь только ОБЪЯВЛЕНИЯ и общие коды ответов. Сами объекты заведены ОДИН раз в
 * apih_sys_common.c: экземпляры контекста службы, буфер ответа со сборщиком,
 * register_service. Копий у них быть не должно — политика «кому что можно» и
 * сборка ответа обязаны быть одни на все службы, иначе три файла разошлись бы в
 * поведении, а одни и те же FID-ы отвечали бы по-разному на одном приборе.
 *
 * Сборщик ответа (sys_w и его буфер) общий на все службы сознательно: обработчики
 * ядра API гоняет ОДНА задача приложения (api_worker_task в app.c зовёт api_worker
 * для AP-ядра, потом для STA-ядра, по одному вызову за такт), поэтому двух
 * одновременно собираемых ответов не бывает — даже если sys.file.* позвали с
 * разных сессий и с разных ядер: вызовы всё равно обслуживаются по очереди.
 * Раскладывать буфер по файлам значило бы держать в памяти три копии по 8 КБ.
 */
#ifndef APIH_SYS_INTERNAL_H
#define APIH_SYS_INTERNAL_H

#include <stddef.h>
#include <stdint.h>

#ifdef APIH_HOST_TEST
/* Хостовые тесты собирают часть служб (apih_fw.c, apih_sys_common.c) без
 * ESP-IDF: им нужна тень app.h, а не сама прошивка. В прошивке условие ложно. */
#  include "apih_sys_app_types.h"
#else
#  include "app.h"
#endif
#include "api.h"
#include "GwJson.h"

/* Коды ответов этой службы (STA): те же, что в api.h, но текстом — страница
 * показывает их как есть. */
#define SYS_OK          "0x00000000"
#define SYS_BAD_ARG     "0x80000003"
#define SYS_NO_MEM      "0x80000006"
#define SYS_NO_ACCESS   "0x80000007"
#define SYS_BUSY        "0x80000008"
#define SYS_TIMEOUT     "0x80000009"
#define SYS_INTERNAL    "0x8000000f"

/* Токенов на разбор ARG запросов конфигурации: несколько строковых полей. */
#define SYS_ARG_MAX_TOKENS 24

/* "aa:bb:cc:dd:ee:ff" — 17 символов и нуль. Формат MAC общий: его печатают и
 * Wi-Fi (wifi.mac, wifi.scan, привязка к точке), и sys.info. */
#define MAC_TEXT_LEN 18

/* ── Экземпляры сервиса ─────────────────────────────────────────────────── *
 *
 * Контекст регистрации: по нему обработчик понимает, через какой транспорт его
 * позвали и что этому клиенту можно. Один и тот же обработчик регистрируется по
 * разу на каждом ядре — с разными контекстами; какой из них получит вызов,
 * решает то, на какое ядро пришёл вызов (см. api_register_handler).
 *
 * Wi-Fi и сетевые настройки меняет только администратор: он подключён к точке
 * доступа, и она — единственный клиент на радио. Клиент станционной сети
 * перестроить шлюз не может, а пока на точке доступа двое, не может никто:
 * второй мог бы подглядывать или вмешаться в обмен. То же условие решает,
 * показывать ли сохранённые пароли.
 *
 * «Ровно один клиент на точке доступа» берётся с СЕТЕВОГО ДРАЙВЕРА
 * (net_wifi_clients_count), а не у транспорта: сколько станций на радио — знает
 * Wi-Fi, а не тот, кто обслуживает соединения.
 */
typedef struct {
    app_context_t *app;
    uint8_t from_ap;     /* вызов пришёл через AP-транспорт (ядро точки доступа) */
    uint8_t may_change;  /* ему разрешено менять состояние (настройки, перезагрузка) */
} sys_service_t;

/* Ядро точки доступа: администратор рядом с прибором — менять можно. */
extern sys_service_t sys_svc_ap;
/* Ядро станции: только чтение. «Не точка доступа» выражено тем, что сервис
 * зарегистрирован на STA-ядре. */
extern sys_service_t sys_svc_ro;
/* Перезагрузка — не настройка: она доступна с любого интерфейса (кнопка на
 * странице не зависит от CAN_CONFIGURE), поэтому на STA-ядре у неё свой
 * контекст: менять можно, но клиент не на точке доступа. Сузить её до точки
 * доступа — зарегистрировать на STA-ядре sys_svc_ro: обработчик ответит
 * AP_ONLY. */
extern sys_service_t sys_svc_mut;

/* ── Ответ клиенту ──────────────────────────────────────────────────────── *
 *
 * Ответ собирается прямо в буфер, без дерева и без узлов: на каждый объект,
 * ключ и значение не выделяется память, и весь ответ не печатается второй раз.
 *
 * Буфер статический, а не на стеке: обработчики обслуживаются по одному, а стек
 * задачи ядра API 8 КБ, тогда как листинг каталога бывает в килобайты. Копию
 * готового текста в конверт ответа делает ядро (api_reply). Хватает с
 * запасом: самый большой ответ — листинг каталога (имя файла до 255 байт плюс
 * размер и признак каталога, то есть ~290 байт на запись), остальные ответы в
 * сотни байт. Не влезло — отвечаем отказом NOMEM, за границу буфера не пишем.
 *
 * Сборщик один на все службы (см. шапку файла); объявлен здесь, потому что
 * обработчики служб дописывают поля в него напрямую. */
#define SYS_RESP_MAX 8192
extern gw_jsonw_t sys_w;

/* Корень ответа — объект; дальше обработчик дописывает поля */
void resp_begin(void);
/* A short machine-readable failure for the configuration page */
void resp_error(const char *sta, const char *err, const char *msg);
void resp_ok(void);
/* Отказ «этому клиенту менять нельзя» с указанием, чего именно не хватает */
void resp_denied(const sys_service_t *svc, uint8_t clients);
/* Отдать ответ клиенту. Буфер сборщика остаётся у службы, а ядро получает
 * готовый текст: оно само положит его в конверт вызова ({"FID":..,"SID":..,
 * "ARG":<json>}) и завершит вызов. Ядро берётся из самого вызова. */
void send_response(void *call);

/* ── Политика ───────────────────────────────────────────────────────────── */

/* Условия на самом приборе: администратор — клиент точки доступа, и он там
 * один. От интерфейса (регистрации) это не зависит: сколько станций на радио,
 * решает драйвер. */
uint8_t config_allowed(const sys_service_t *svc, uint8_t clients);
/* Можно ли этому клиенту менять состояние: экземпляр сервиса это позволяет
 * (регистрация на интерфейс) и условия на приборе выполнены. */
uint8_t change_allowed(const sys_service_t *svc, uint8_t clients);

/* Контекст регистрации: по нему обработчик понимает, через какой интерфейс его
 * вызвали. У методов без политики (echo, sys.files) контекста нет — NULL. */
const sys_service_t *svc_of(void **context);

/* Регистрация экземпляра сервиса: что за метод, на каком ядре он оказан и с
 * каким контекстом. Один и тот же обработчик регистрируется по разу на каждом
 * ядре — этим и выражена политика (см. sys_service_t). */
uint8_t register_service(api_t *api, api_handler_t handler, const char *fid,
                         void *context);

/* ── MAC-адрес текстом ──────────────────────────────────────────────────── */

/* "aa:bb:cc:dd:ee:ff", "aa-bb-…", "aabb.ccdd.eeff" или просто 12 hex-цифр.
 * 0 — разобрать не удалось (в out при этом ничего осмысленного). */
uint8_t mac_parse(const char *s, uint8_t *out);
void    mac_text(const uint8_t *mac, char *out, size_t out_size);

/* Текущий адрес интерфейса спрашиваем у драйвера, а не у своих записей: после
 * перезагрузки истина только там, а наши записи — это «что заказано». Нужен и
 * wifi.mac, и sys.info (оба показывают, чем прибор работает в эфире СЕЙЧАС). */
void mac_runtime(wifi_interface_t iface, const uint8_t *factory, char *out, size_t out_size);

/* ── Подготовка и точки входа служб ─────────────────────────────────────── */

/* Подготовить общее состояние службы (буфер сборщика ответов и экземпляры
 * контекста). Зовётся ОДИН раз из api_sys_run до первой регистрации. */
void apih_sys_common_init(app_context_t *app);

/* Регистраторы: каждый файл службы регистрирует свои FID на обоих ядрах и
 * возвращает ESP_OK, только если ВСЕ его регистрации прошли (это решает одна
 * общая ok-переменная). */
esp_err_t apih_wifi_run(app_context_t *app);    /* wifi.sta/ap/mac/scan */
esp_err_t apih_device_run(app_context_t *app);  /* sys.info, sys.net, sys.reboot */
esp_err_t apih_files_run(app_context_t *app);   /* sys.files, sys.file.* */
/* sys.fw.begin/write/end/abort — только AP-ядро (прошивка со станции не
 * принимается, см. apih_fw.c). */
esp_err_t apih_fw_run(app_context_t *app);

#endif /* APIH_SYS_INTERNAL_H */
