#pragma once

#include <stdint.h>

/* ── Кольцевой буфер приёма порта ────────────────────────────────────────────
 *
 * Хранит принятое из порта кусками [метка][данные]:
 *
 *     +--------+---------------+--------+---------------+--------+--------
 *     | метка  | данные куска  | метка  | данные куска  | метка  | данные…
 *     +--------+---------------+--------+---------------+--------+--------
 *        2 Б        длина          2 Б        длина        2 Б
 *
 * Метка (16 бит, младшим байтом вперёд):
 *     0x0000        — кусок ОТКРЫТ, данные ещё пишутся;
 *     0x0001..0x7FFF — длина куска, КАДР ЗАКОНЧИЛСЯ (линия замолчала);
 *     0x8001..0xFFFF — длина куска, КАДР ПРОДОЛЖАЕТСЯ: кусок закрыт либо по
 *                      порогу частичной выгрузки, либо по излому кольца, но
 *                      конец передачи на линии ещё не наступил.
 *
 * Метка открытого куска заполняется ЗАДНИМ ЧИСЛОМ — по сохранённому индексу
 * (open_mark), когда кусок закрывается. Читатель до открытой метки не доходит:
 * он идёт по готовым кускам и останавливается на первой метке со значением 0.
 *
 * Что это даёт:
 *   • границы передач (пауз на линии) пишутся в момент приёма, а не при отдаче,
 *     поэтому отдача может агрегировать сколько угодно кусков в одно сообщение и
 *     ничего при этом не склеивает;
 *   • длинный кадр, не дождавшийся конца передачи, выгружается частями с
 *     признаком «продолжение» — клиент склеивает подряд идущие продолжения и
 *     закрывает кадр на первой метке без признака;
 *   • число кусков не ограничено ничем, кроме размера кольца: кадры хоть по
 *     одному байту, у каждого своя метка.
 *
 * Переполнение (голова догнала ещё не забранные данные) НЕ перепрыгивает
 * читателя: новый кусок просто не пишется, выставляется признак потери, а то,
 * что ещё не забрано, остаётся читателю целым. Молчаливой склейки двух передач
 * в одну при этом не бывает.
 *
 * Владение памятью: само кольцо (массив байт) выделяет вызывающий и передаёт в
 * init. У библиотеки нет ни одной своей переменной — всё состояние в дескрипторе.
 *
 * Блокировок внутри нет: вызывающий сам решает, чем защищать push и take друг от
 * друга (запись идёт из задачи событий UART, чтение — из задачи сервиса).
 */

/* Сколько байт отводится под состояние дескриптора. Само состояние — 13 байт на
 * 32-битной цели (указатель, четыре индекса, признак), но блок взят с запасом:
 * те же файлы собираются и тестовым прогоном на хосте, где указатель 8 байт. */
#define GW_UART_RXBUF_PRIVATE_SIZE   32

typedef struct {
    uint32_t __private[GW_UART_RXBUF_PRIVATE_SIZE / sizeof(uint32_t)];
} gw_uart_rxbuf_t;

/* Метка: 2 байта. */
#define GW_UART_RXBUF_MARK_SIZE      2
/* Признак «кадр продолжается» в старшем бите метки. */
#define GW_UART_RXBUF_FLAG_MORE      0x8000
/* Предел длины одного куска (младшие 15 бит метки). */
#define GW_UART_RXBUF_MAX_PIECE      0x7FFF

/* Порог частичной выгрузки: открытый кусок длиннее этого закрывается с
 * признаком «продолжение», не дожидаясь конца передачи на линии. Это не
 * свойство линии, а компромисс «задержка против мелочи в канале», поэтому
 * константа. */
#define GW_UART_RXBUF_PART_THRESHOLD 1024

/* Готовый кусок, отданный читателю. */
typedef struct {
    uint16_t len;          /* сколько байт скопировано в приёмник читателя */
    uint8_t  frame_end;    /* 1 — кадр закончился, 0 — продолжение следует */
    uint8_t  lost_before;  /* перед этими байтами приём терялся (был разрыв) */
} gw_uart_rxbuf_piece_t;

/* Инициализация: кольцо storage размером size байт. size — не меньше
 * GW_UART_RXBUF_MARK_SIZE * 4. Возвращает 1 при успехе. */
uint8_t  gw_uart_rxbuf_init(void *desc, uint8_t *storage, uint16_t size);

/* Положить принятое в кольцо. frame_end — линия замолчала после этих байт
 * (значит, передача на ней закончилась). Возвращает, сколько байт принято;
 * меньше len — не хватило места, выставлен признак потери. */
uint16_t gw_uart_rxbuf_push(void *desc, const uint8_t *data, uint16_t len,
                            uint8_t frame_end);

/* Посмотреть очередной готовый кусок, ничего не забирая: сколько в нём байт и
 * с какими признаками. Нужно, чтобы решить, влезет ли он в сообщение целиком —
 * забранный кусок вернуть в кольцо нельзя. */
uint8_t  gw_uart_rxbuf_peek(const void *desc, uint16_t *len, uint8_t *frame_end,
                            uint8_t *lost_before);

/* Забрать очередной готовый кусок в dst (не меньше размера кольца — кусок
 * целиком). Возвращает 1, если кусок был; в piece — его длина и признаки.
 * 0 — готовых кусков нет (либо в кольце только открытый кусок). Если кусок не
 * влезает в max, возвращает 0 и кладёт требуемую длину в piece->len. */
uint8_t  gw_uart_rxbuf_take(void *desc, uint8_t *dst, uint16_t max,
                            gw_uart_rxbuf_piece_t *piece);

/* Был ли разрыв приёма (данные терялись). Признак живёт до lost_clear. */
uint8_t  gw_uart_rxbuf_lost(const void *desc);
void     gw_uart_rxbuf_lost_clear(void *desc);

/* Диагностика: сколько байт кольца занято (включая метки) и сколько свободно. */
uint16_t gw_uart_rxbuf_used(const void *desc);
uint16_t gw_uart_rxbuf_free(const void *desc);
