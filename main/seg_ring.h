#pragma once

#include <stdint.h>

/* ── Сегментированный кольцевой буфер ────────────────────────────────────────
 *
 * Кольцо байт, разрезанное на сегменты:
 *
 *     +-------+-------------+-------+-------------+-------+------
 *     | метка |   данные    | метка |   данные    | метка | данные…
 *     +-------+-------------+-------+-------------+-------+------
 *        2 Б      длина         2 Б      длина        2 Б
 *
 * Сегмент — это кусок потока, который пишущий пометил как законченный (например,
 * линия замолчала). Метка (16 бит, ЗНАКОВАЯ, младшим байтом вперёд) — это длина
 * того, что ещё не прочитано:
 *
 *     0             — сегмент ОТКРЫТ: в него ещё пишут, кадр продолжается;
 *     больше нуля   — столько байт данных, приём шёл нормально;
 *     меньше нуля   — столько же байт (по модулю), но при приёме что-то потеряно.
 *
 * Флагов нет вовсе: знак и есть признак потери, а записанная длина (любого
 * знака) — признак того, что кадр закончился. Пока метка не записана, сегмент
 * продолжается.
 *
 * Отдельно есть ПУСТАЯ метка — ноль НЕ на месте метки пишущегося сегмента: это
 * разрыв без данных (кадр кончился, а байтов под него не было: их уже забрали
 * или они потерялись). Читатель отдаёт на ней кусок нулевой длины с концом
 * кадра и идёт дальше; для потери пишется пустая метка со знаком минус
 * (значение вне допустимых длин).
 *
 * Признаки стоят на границе сегмента и относятся к тому, что ПЕРЕД ними:
 * «потеря» — это потеря после отданных байт, а не перед ними.
 *
 * ── Контракт ────────────────────────────────────────────────────────────────
 *
 *   init  — отдать кольцо (память выделяет вызывающий) и размер;
 *   write — положить принятое, с признаком «сегмент закончен»;
 *   read  — забрать данные (или, без приёмника, справиться о текущем сегменте);
 *   used  — сколько байт кольца занято;
 *   free  — сколько свободно.
 *
 * read отдаёт НЕ БОЛЬШЕ, чем просят, и никогда не переступает границу
 * сегмента: либо ровно max байт (сегмент длиннее), либо остаток сегмента с
 * признаком его конца. Прочитанное кольцо не хранит: при частичном чтении
 * метка сегмента переезжает за прочитанные байты, а её значение уменьшается на
 * прочитанное, поэтому уже отданное место свободно сразу и отдельного счётчика
 * «сколько отдано» не нужно.
 *
 * Признаки потери и конца приходят вместе с последними байтами сегмента; если
 * сегмент к этому моменту уже отдан (конец наступил позже), они приходят
 * отдельным куском с len == 0 — данные и разметка не смешиваются. Признак
 * потери ставится вместе с длиной в метке, поэтому потеря всегда означает и
 * конец кадра: данные после неё не приняты.
 *
 * Указателей на внутренности буфера наружу не отдаётся: кусок описывает
 * структура gw_seg_ring_chunk_t. Отдавать адрес данных нельзя — при изломе
 * кольца или перезаписи он станет недействительным, а служебные метки лежат в
 * том же массиве и не должны быть доступны на запись.
 *
 * Переполнение (голова догнала ещё не прочитанное) не перепрыгивает читателя:
 * новые данные не пишутся, а к концу последнего записанного сегмента
 * приписывается признак потери. Прочитанное остаётся целым, склеить две
 * передачи в одну молча нельзя.
 *
 * Через конец кольца сегмент не переходит: непрочитанное при необходимости
 * переносится в начало (один memmove на оборот кольца). Иначе позиции «пусто» и
 * «полно» давали бы одно и то же значение.
 *
 * Блокировок внутри нет: вызывающий сам решает, чем защищать write и read друг
 * от друга (обычно — рекурсивный мьютекс вызывающего).
 */

/* Сколько байт отводится под состояние дескриптора. Само состояние — 24 байта
 * на 64-битной цели, но те же файлы собираются и для 32-битной (ESP32): блок
 * взят с запасом, чтобы размер не зависел от разрядности. */
#define GW_SEG_RING_PRIVATE_SIZE     32

typedef struct {
    uint32_t __private[GW_SEG_RING_PRIVATE_SIZE / sizeof(uint32_t)];
} gw_seg_ring_t;

/* Кусок, который отдаёт read. */
typedef struct {
    uint16_t len;    /* байт данных (0 — кусок несёт только признаки) */
    uint8_t  end;    /* 1 — на этих байтах сегмент кончился */
    uint8_t  lost;   /* 1 — сразу после этих байт данные терялись */
} gw_seg_ring_chunk_t;

/* Инициализация: кольцо storage размером size байт. size — не меньше
 * GW_SEG_RING_MARK_SIZE * 4. Возвращает 1 при успехе. */
uint8_t  gw_seg_ring_init(void *desc, uint8_t *storage, uint16_t size);

/* Положить данные в кольцо. segment_end — сегмент закончился на этих байтах
 * (сегмент можно закончить и пустой записью: len == 0, segment_end == 1).
 * Возвращает, сколько байт принято; меньше len — места не хватило, к концу
 * записанного приписан признак потери. */
uint16_t gw_seg_ring_write(void *desc, const uint8_t *data, uint16_t len, uint8_t segment_end);

/* Забрать данные текущего сегмента.
 *
 *   dst != NULL — скопировать не больше max байт в dst и снять их с кольца;
 *   dst == NULL — ничего не снимать, только описать текущий сегмент (сколько
 *                 в нём ещё есть и с какими признаками).
 *
 * Возвращает 1, если есть что отдать или о чём сообщить, 0 — если кольцо пусто
 * (или в нём только ещё не законченный сегмент, у которого ничего не осталось).
 * В chunk: len — сколько байт, end — сегмент кончился, lost — после этих байт
 * была потеря. Кусок с len == 0 несёт только признаки. */
uint8_t  gw_seg_ring_read(void *desc, uint8_t *dst, uint16_t max,
                          gw_seg_ring_chunk_t *chunk);

uint16_t gw_seg_ring_free(const void *desc);
